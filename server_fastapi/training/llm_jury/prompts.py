"""
Шаблон промпта для LLM-жюри (см. план AI Training Python Stack, раздел 3).

Подстановки: [РОЛЬ], [КОНТЕКСТ], [ТИКЕР], [СПИСОК_ИНСТРУМЕНТОВ]. Парсинг: action (BUY/SELL/HOLD), confidence [0,1]
(одиночный запрос — текстовый блок с CONFIDENCE; батч — JSON instruments[]).
"""

from __future__ import annotations

# Как сочетать данные системы и внешний контур (поиск / актуальные знания).
_JURY_DATA_PLUS_SEARCH = """Источники — используй вместе, в одном анализе:
1) Данные из системы: строка инструмента ниже (FIGI, тикер, свечи, контекст из БД). Это опорная фактура: не выдумывай цифры, которых нет в строке и которые ты не подтвердил внешним источником.
2) Веб-поиск и актуальные знания: дополняй и проверяй котировки, объёмы за последние дни, новости, дивиденды, сектор, сравнение с индексом (IMOEX, S&P 500 и т.д.). Если у тебя есть инструмент веб-поиска — применяй его по тикеру и эмитенту; если поиска нет — используй актуальные знания на дату и явно опирайся на строку из системы там, где внешние данные недоступны.
Для каждого факта извне системы укажи источник (название, дата или URL). Противоречия между строкой БД и внешними данными кратко отрази в обосновании и снизь confidence, если картина неоднозначна.
"""

# Общие ориентиры по сигналам (и для одиночного, и для батча).
_JURY_SIGNAL_GUIDELINES = """Правила принятия решений (по данным в контексте; оценивай только то, что можно обосновать):
1) SELL, confidence обычно 0.55–0.90, если: цена снижается несколько дней подряд или заметное падение за короткое окно; ослабление на росте объёма; явный негатив в фактах из контекста.
2) BUY, confidence обычно 0.55–0.90, если: устойчивый рост по свечам; пробой вверх на повышенных объёмах; явный позитив в фактах из контекста. (RSI/MACD — только если ты их посчитал по переданным ценам или нашёл в источнике.)
3) HOLD, confidence обычно 0.50–0.65 — смешанная картина, боковик, мало данных или противоречивые сигналы.
Если по инструменту данных недостаточно — HOLD и confidence около 0.50; не обнуляй confidence без причины.
"""

JURY_PROMPT_TEMPLATE = """Ты [РОЛЬ]. Дай независимый вердикт по инструменту [ТИКЕР]: BUY, SELL или HOLD и уровень уверенности confidence от 0 до 1.

""" + _JURY_DATA_PLUS_SEARCH + """

ДАННЫЕ ИЗ СИСТЕМЫ:
[КОНТЕКСТ]

""" + _JURY_SIGNAL_GUIDELINES + """

Верни ответ СТРОГО в формате (без markdown и лишнего текста):
ACTION: BUY|SELL|HOLD
CONFIDENCE: 0.00-1.00   (обязательно; число с точкой, например 0.62)
HORIZON: short|mid|long
SOURCES: (опционально) кратко: факт — источник, дата
REASONS:
- <ключевой драйвер 1>
- <ключевой драйвер 2>
- <ключевой риск>
TRIGGERS:
- up: <что подтвердит BUY>
- down: <что подтвердит SELL>
POSITION_SIZE_HINT:
- <низкий|средний|высокий риск позиции и почему>

Ограничения:
- текст ответа только на русском языке (кроме латиницы в ACTION/HORIZON);
- максимум 180 слов;
- CONFIDENCE — субъективная уверенность в верности ACTION: при явном BUY/SELL обычно не ниже ~0.40; 0.00 не использовать, если выбрано осмысленное действие.
"""


def build_jury_prompt(
    ticker: str,
    context: str,
    role: str = "финансовый аналитик",
) -> str:
    """
    Подставляет в шаблон тикер, контекст и роль.
    context: данные инструмента (сектор, цены, объёмы, макро-сводка).
    """
    return JURY_PROMPT_TEMPLATE.replace("[РОЛЬ]", role).replace(
        "[КОНТЕКСТ]", context
    ).replace("[ТИКЕР]", ticker)


JURY_BATCH_PROMPT_TEMPLATE = """Ты [РОЛЬ]. Задача: для КАЖДОГО инструмента из списка ниже дать независимый вердикт — BUY, SELL или HOLD — и уверенность confidence от 0 до 1.

""" + _JURY_DATA_PLUS_SEARCH + """

По каждому инструменту в списке: сначала учти его строку (FIGI, тикер, свечи из системы), затем через веб-поиск или актуальные знания уточни при необходимости динамику и объёмы, новости, сектор, сравнение с индексом. Технические индикаторы (RSI, MACD, MA) — только если посчитал по ценам из строки или нашёл в проверяемом источнике. Ориентиры источников: агрегаторы котировок, биржевые раскрытия, новостные ленты. Если для позиции внешние данные недоступны — вердикт по строке списка и confidence сдержанный (около 0.50 при HOLD).

""" + _JURY_SIGNAL_GUIDELINES + """

Формат ответа — СТРОГО один JSON-объект (без markdown, без текста до или после):
{"instruments":[{"figi":"<FIGI>","action":"BUY|SELL|HOLD","confidence":0.62}]}

Требования к JSON:
- Ровно одна запись в instruments на каждый FIGI из списка ниже, без пропусков и дубликатов figi; figi — точное совпадение с полем из строки.
- confidence — число с плавающей точкой от 0 до 1 (например 0.58); для HOLD при нехватке данных — около 0.50; не заполняй все инструменты нулевой уверенностью.
- Ключи только латиницей: instruments, figi, action, confidence; action — BUY, SELL или HOLD.

Список инструментов для анализа:
[СПИСОК_ИНСТРУМЕНТОВ]
"""


def build_jury_batch_prompt(
    instrument_lines: list[str],
    role: str = "финансовый аналитик",
) -> str:
    """
    instrument_lines: строки вида «FIGI=...; тикер ...; ...» для каждого инструмента чанка.
    """
    body = "\n".join(instrument_lines) if instrument_lines else "(пусто)"
    return (
        JURY_BATCH_PROMPT_TEMPLATE.replace("[РОЛЬ]", role).replace("[СПИСОК_ИНСТРУМЕНТОВ]", body)
    )
